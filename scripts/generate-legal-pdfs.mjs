/**
 * Regenerates the legal PDFs FROM the published web pages.
 *
 *   npm run build && npx vite preview --port 4173 --strictPort &
 *   node scripts/generate-legal-pdfs.mjs
 *
 * WHY THIS EXISTS: the PDFs and the web pages were maintained separately and
 * drifted. On 2026-08-18 the PDF (and the page) claimed bank transactions were
 * "not stored" while 2,039 rows sat in the database, omitted Anthropic from the
 * processor list while the AI Assistant sent holdings to it, and pointed at the
 * old mizan-puce.vercel.app host. Two copies of the same policy will always
 * diverge eventually; the fix is to stop having two sources.
 *
 * The WEB PAGE is now the single source of truth. The PDF is a rendering of it,
 * regenerated by this script — never hand-edited. That also means the tests in
 * src/test/legal.test.js, which assert against the JSX, transitively cover the
 * PDF as well.
 *
 * All five legal documents are generated here. Security, Data Retention and
 * Access Controls were PDF-only until 2026-08-18; converting them revealed the
 * same drift as the Privacy Policy — a stale host, the false "transactions are
 * not stored" claim, a missing Anthropic vendor entry, and a retention schedule
 * listing a `sessions` table that does not exist while omitting fourteen that
 * do. Generating from the pages is what stops that recurring.
 */
import { chromium } from "@playwright/test";
import fs from "node:fs";
import path from "node:path";

const BASE = process.env.PREVIEW_URL || "http://localhost:4173";
const OUT_PUBLIC = path.resolve("public/legal");
const OUT_REPO   = path.resolve("legal");

const DOCS = [
  { route: "/privacy",         file: "PRIVACY_POLICY.pdf" },
  { route: "/terms",           file: "TERMS_OF_SERVICE.pdf" },
  { route: "/security",        file: "SECURITY_POLICY.pdf" },
  { route: "/data-retention",  file: "DATA_RETENTION_POLICY.pdf" },
  { route: "/access-controls", file: "ACCESS_CONTROLS_POLICY.pdf" },
];

async function requirePreview() {
  try {
    const r = await fetch(BASE, { signal: AbortSignal.timeout(3000) });
    if (r.ok) return;
  } catch { /* fall through */ }
  console.error(
    `No preview server at ${BASE}.\n\n` +
    `  npm run build && npx vite preview --port 4173 --strictPort\n\n` +
    `then re-run this script (or set PREVIEW_URL).`,
  );
  process.exit(1);
}

const run = async () => {
  await requirePreview();
  fs.mkdirSync(OUT_PUBLIC, { recursive: true });
  fs.mkdirSync(OUT_REPO, { recursive: true });

  const browser = await chromium.launch();
  // Force the LIGHT theme: these are printed documents, and a dark-mode PDF is
  // both unreadable on paper and a compliance reviewer's least favourite thing.
  const ctx = await browser.newContext({
    colorScheme: "light",
    viewport: { width: 1024, height: 1400 },
    serviceWorkers: "block",
  });

  for (const { route, file } of DOCS) {
    const page = await ctx.newPage();
    await page.addInitScript(() => {
      try { localStorage.setItem("mizan_theme_mode", "light"); } catch { /* private mode */ }
    });
    await page.goto(BASE + route, { waitUntil: "domcontentloaded" });
    // Wait for the heading, then for fonts — a PDF captured mid font-swap has
    // the wrong metrics and reflows the whole document.
    await page.locator("h1").first().waitFor({ state: "visible", timeout: 15_000 });
    await page.evaluate(() => document.fonts?.ready).catch(() => {});
    await page.waitForTimeout(300);

    // Hide the in-page nav chrome: useful on the web, noise on paper.
    await page.addStyleTag({ content: `
      nav, .mz-legal-nav, footer a[href$=".pdf"] { display: none !important; }
      body { background: #fff !important; }
    ` });

    const buf = await page.pdf({
      format: "Letter",
      printBackground: true,
      margin: { top: "0.75in", bottom: "0.75in", left: "0.75in", right: "0.75in" },
    });
    for (const dir of [OUT_PUBLIC, OUT_REPO]) fs.writeFileSync(path.join(dir, file), buf);
    console.log(`  ${file}  ${(buf.length / 1024).toFixed(0)}KB  ← ${route}`);
    await page.close();
  }

  await browser.close();

  // Verify rather than trust: a PDF that renders an error page is still a PDF.
  let bad = 0;
  for (const { file } of DOCS) {
    const p = path.join(OUT_PUBLIC, file);
    const head = fs.readFileSync(p).subarray(0, 5).toString("latin1");
    const size = fs.statSync(p).size;
    if (head !== "%PDF-" || size < 20_000) {
      console.error(`FAIL ${file}: header=${head} size=${size}`);
      bad++;
    }
  }
  process.exitCode = bad ? 1 : 0;
};

run().catch((e) => { console.error(e); process.exit(1); });
